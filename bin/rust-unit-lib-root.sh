# Generate a deterministic unit-library crate root that `pub mod`s top-level
# library sources. Heuristic only: excludes files already referenced as
# `mod name` from another candidate (or lib.rs). Not a Rust parser.
#
# Usage: rust-unit-lib-root.sh <outfile> <modules-stamp> <src.rs>...
set -euo pipefail

if [[ $# -lt 2 ]]; then
	echo "usage: $0 outfile modules-stamp [src.rs ...]" >&2
	exit 2
fi

out=$1
stamp=$2
shift 2
srcs=("$@")

# Prefer authoritative handwritten lib.rs — never overwrite it.
if [[ -f lib.rs ]]; then
	printf 'lib.rs\n' > "$stamp.tmp"
	if ! cmp -s "$stamp.tmp" "$stamp" 2>/dev/null; then
		mv -f "$stamp.tmp" "$stamp"
	else
		rm -f "$stamp.tmp"
	fi
	exit 0
fi

# Sort for deterministic output
mapfile -t sorted < <(printf '%s\n' "${srcs[@]}" | sed '/^$/d' | sort -u)

# Drop sources that another library source already pulls in via `mod name`
# (fixed-string grep; comments/macros/cfg can false-positive — see RUST.md).
roots=()
for f in "${sorted[@]}"; do
	[[ -f "$f" ]] || continue
	base=$(basename "$f" .rs)
	# skip reserved
	case "$base" in
		mod|lib|build|rs_unit_lib) continue ;;
	esac
	used=0
	for g in "${sorted[@]}" lib.rs; do
		[[ -f "$g" ]] || continue
		[[ "$g" == "$f" ]] && continue
		if grep -Fq "mod ${base}" "$g" 2>/dev/null; then
			used=1
			break
		fi
	done
	if [[ $used -eq 0 ]]; then
		roots+=("$f")
	fi
done

list=$(printf '%s\n' "${roots[@]}" | sed '/^$/d')
printf '%s\n' "$list" > "$stamp.tmp"
if cmp -s "$stamp.tmp" "$stamp" 2>/dev/null && [[ -f "$out" ]]; then
	rm -f "$stamp.tmp"
	exit 0
fi
mv -f "$stamp.tmp" "$stamp"

tmp="${out}.tmp.$$"
{
	echo '// @generated by rust-unit-lib-root.sh — do not edit'
	echo '// Unit library crate root (auto). Handwritten lib.rs, if present, wins.'
	echo
	for f in "${roots[@]}"; do
		base=$(basename "$f" .rs)
		# Rust module identifiers: sanitize like crate names lightly
		mod=$(printf '%s' "$base" | sed -e 's/-/_/g' -e 's/[^A-Za-z0-9_]/_/g')
		if [[ "$mod" =~ ^[0-9] ]]; then
			mod="m_${mod}"
		fi
		if [[ "$mod" != "$base" ]]; then
			echo "#[path = \"${f}\"]"
			echo "pub mod ${mod};"
		else
			echo "pub mod ${mod};"
		fi
	done
} > "$tmp"
mv -f "$tmp" "$out"
